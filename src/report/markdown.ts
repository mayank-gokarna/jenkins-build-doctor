import { displayPath } from '../jenkins/paths';
import { CATEGORY_LABELS, type Diagnosis, type Finding } from '../analysis/types';
import { formatDuration } from './html';

/** Markdown export of a diagnosis, for pasting into tickets or chat. */
export function diagnosisToMarkdown(d: Diagnosis, aiText?: string): string {
  const out: string[] = [];
  const b = d.build;
  out.push(`# ${displayPath(d.job.path)} #${b.number}: ${b.status.toUpperCase()}`);
  out.push('');
  out.push(`**${d.headline}**`);
  out.push('');
  const meta = [
    b.timestamp ? `Started: ${new Date(b.timestamp).toISOString()}` : '',
    `Duration: ${formatDuration(b.durationMs)}`,
    b.builtOn ? `Agent: ${b.builtOn}` : '',
    b.branch ? `Branch: ${b.branch}` : '',
    b.commit ? `Commit: ${b.commit.slice(0, 12)}` : '',
    b.webUrl ? `URL: ${b.webUrl}` : '',
  ].filter(Boolean);
  out.push(meta.map((m) => `- ${m}`).join('\n'));
  if (d.failedStages.length) {
    out.push(`- Failed stage(s): ${d.failedStages.map((s) => s.name).join(', ')}`);
  }

  const section = (title: string, findings: Finding[]) => {
    if (findings.length === 0) {
      return;
    }
    out.push('', `## ${title}`);
    for (const f of findings) {
      out.push('', `### ${f.title} (${CATEGORY_LABELS[f.category]}, ${f.certainty === 'confirmed' ? 'confirmed' : 'hypothesis'})`);
      out.push(f.summary);
      if (f.evidence.length) {
        out.push('', '```text');
        for (const e of f.evidence.slice(0, 3)) {
          out.push(`${e.line ? `L${e.line}: ` : ''}${e.text}`);
        }
        out.push('```');
      }
      if (f.causes.length) {
        out.push('', 'Probable causes (hypotheses):', ...f.causes.map((c) => `- ${c}`));
      }
      if (f.remediation.length) {
        out.push('', 'Remediation:', ...f.remediation.map((r, i) => `${i + 1}. ${r}`));
      }
    }
  };

  section('Most probable root cause', d.primary ? [d.primary] : []);
  const rest = d.findings.filter((f) => !f.symptom && f !== d.primary);
  section('Other confirmed findings', rest.filter((f) => f.certainty === 'confirmed'));
  section('Hypotheses', rest.filter((f) => f.certainty === 'hypothesis'));

  if (d.failedTests.length) {
    out.push('', '## Failing tests');
    for (const t of d.failedTests.slice(0, 20)) {
      out.push(`- \`${t.className ? `${t.className}.` : ''}${t.name}\`: ${(t.errorDetails ?? '').split('\n')[0].slice(0, 200)}`);
    }
  }
  if (aiText) {
    out.push('', '## AI analysis (unverified)', '', aiText);
  }
  if (d.notes.length) {
    out.push('', '## Notes', ...d.notes.map((n) => `- ${n}`));
  }
  out.push('', '_Generated by Jenkins Build Doctor (rule-based analysis)._');
  return out.join('\n');
}
