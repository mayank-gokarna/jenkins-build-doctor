import type { RuleDefinition, RuleMatch } from '../types';

const EXIT_CODE_MEANINGS: Record<string, string> = {
  '1': 'Exit code 1 is a generic failure; the command\'s own output just above explains why.',
  '2': 'Exit code 2 usually means a usage error (bad arguments/flags) or, for make, a failed target.',
  '126': 'Exit code 126: the command was found but is not executable (permissions / wrong interpreter).',
  '127': 'Exit code 127: command not found — the tool is missing from the agent or not on PATH.',
  '130': 'Exit code 130: interrupted (SIGINT).',
  '134': 'Exit code 134: aborted (SIGABRT) — often an assertion or native crash.',
  '137': 'Exit code 137: killed with SIGKILL — typically out of memory (container limit / OOM killer).',
  '139': 'Exit code 139: segmentation fault (SIGSEGV) in a native process.',
  '143': 'Exit code 143: terminated with SIGTERM — typically an abort or timeout.',
};

function exitCodeEnrichment(matches: RuleMatch[]) {
  const codes = [...new Set(matches.map((m) => m.groups[0]).filter((c): c is string => !!c))];
  const causes = codes.map((c) => EXIT_CODE_MEANINGS[c]).filter((s): s is string => !!s);
  return { causes };
}

